"""Small standalone module skeletons, derived from pinned official SDK templates."""
import json
from pathlib import Path
import re
import shutil
import uuid
from sdk import TYPES, digest, run, validate

BUILD = '''const std = @import("std");
pub fn build(b: *std.Build) void {
    const sdk_build = b.lazyImport(@This(), "r4os_sdk") orelse return;
    const dependency = b.dependencyFromBuildZig(sdk_build, .{});
    const sdk = sdk_build.sdk(b, dependency, .{});
    _ = sdk.addR4MF(b.path("module.R4MF"));
}
'''

DRIVER = '''const r4os = @import("r4os");
comptime { asm (r4os.r4dev.driverEntriesAsm("project_init", "project_shutdown")); }
export fn project_init(api: *const r4os.r4dev.DriverApi) callconv(.c) i32 {
    const context = r4os.r4dev.DriverContext.init(api);
    return if (context.apiCompatible()) 0 else -3;
}
export fn project_shutdown() callconv(.c) i32 { return 0; }
'''

PROTOCOL = '''const r4os = @import("r4os");
comptime { asm (r4os.r4dev.protocolEntriesAsm("project_init", "project_shutdown", "project_query", "project_dispatch")); }
export fn project_init(api: *const r4os.r4dev.ProtocolApi) callconv(.c) i32 {
    var context = r4os.r4dev.ProtocolContext.init(api);
    return context.registerRole("misc.{role}", .misc, 0);
}
export fn project_shutdown() callconv(.c) i32 { return 0; }
export fn project_query(out: *r4os.abi.ProtocolStatus) callconv(.c) i32 {
    out.* = .{ .state = @intFromEnum(r4os.abi.ProtocolState.active), .flags = 0,
        .last_error = 0, .reserved = 0, .note = .{0} ** 64 };
    return 0;
}
export fn project_dispatch(op: u32, input: *const r4os.abi.ProtocolBuffer, output: *r4os.abi.ProtocolBuffer) callconv(.c) i32 {
    _ = op; _ = input; _ = output;
    return -4;
}
'''


def write(directory, relative, text):
    path = directory / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def fill(text, values):
    for key, value in values.items():
        text = text.replace('{' + key + '}', str(value))
    return text


def library(context, directory, project):
    name = project['moduleName']
    lower = name.lower()
    template = context['paths']['sdk'] / 'Templates/R4L/Zig'
    ident = uuid.UUID(project['id']).int
    values = {'ProjectName': name, 'ProjectNameLower': lower, 'Version': '0.1.0',
              'Target': '/R4OS/LIBRARIES/' + name + '.R4L', 'ImageScope': 'none',
              'Description': 'Runtime library', 'InterfaceIdLow': ident & ((1 << 64) - 1),
              'InterfaceIdHigh': ident >> 64}
    manifest = fill((template / 'module.R4MF.template').read_text(), values)
    manifest = manifest.replace('# Generated by New-R4LProject.ps1;', '# Derived from the official SDK R4L template;').replace('META=generator=New-R4LProject.ps1', 'META=generator=R4OS-Studio')
    if project['language'] == 'C':
        manifest = manifest.replace('LANGUAGE=Zig', 'LANGUAGE=C').replace('SOURCE=Source/main.zig', 'SOURCE=Source/main.c')
    write(directory, 'module.R4MF', manifest)
    write(directory, 'Contract/LibraryContract.json', fill((template / 'Contract/LibraryContract.json.template').read_text(), values))
    paths = {'contract': 'Contract/LibraryContract.json', 'baseline': 'Contract/LibraryContract.baseline.json',
             'implementation-zig': 'Contract/Generated/implementation_abi.zig',
             'binding-zig': f'Bindings/Zig/{lower}.zig', 'binding-c': f'Bindings/C/{lower}.h',
             'fixture-zig': 'Tests/Generated/contract_conformance.zig',
             'fixture-c': 'Tests/Generated/contract_conformance.c', 'docs': 'Docs/API.md'}
    for path in paths.values():
        (directory / path).parent.mkdir(parents=True, exist_ok=True)
    generator = context['cache'] / 'r4l-contract-gen'
    # The SDK package was checked by profile(); compiler tracks the exact source.
    run([context['paths']['zig'] / 'zig', 'build-exe', '-OReleaseSafe',
         context['paths']['sdk'] / 'Tools/R4LContractGen/src/main.zig', '-femit-bin=' + str(generator)], context['env'])
    args = [generator, '--write', '--update-baseline', '--module-name', name, '--export', f'API_V1:{lower}_api_v1:1']
    for option, path in paths.items():
        args.extend(['--' + option, directory / path])
    run(args, context['env'])
    if project['language'] == 'Zig':
        write(directory, 'Source/main.zig', fill((template / 'Source/main.zig.template').read_text(), values))
    else:
        header = (directory / f'Bindings/C/{lower}.h').read_text()
        # Use the generated ABI table, whose identity/layout belongs to the contract.
        write(directory, 'Source/main.c', f'''#include <r4os/abi.h>
#include "{lower}.h"
__attribute__((section(".text.r4l_entry"), used)) void r4l_entry(void) {{}}
int64_t {lower}_add_impl(int64_t left, int64_t right) {{ return (int64_t)((uint64_t)left + (uint64_t)right); }}
__attribute__((section(".data.r4l_exports"), used, aligned(8)))
{name}ApiV1 {lower}_api_v1 = {{
    .header = {name}_API_V1_HEADER_INITIALIZER,
    .add = {lower}_add_impl,
}};
__attribute__((section(".data.r4l_exports"), used, aligned(8)))
R4LQuery {lower}_query = {{ .magic = R4L_ABI_MAGIC, .abi_version = R4L_ABI_VERSION,
    .size = R4L_QUERY_STRUCT_SIZE, .group = 0, .kernel_bridge = 0, .reserved = 0 }};
''')
        if not header:
            raise ValueError('The SDK did not generate the C binding.')


def render(context, directory, project):
    name = project['moduleName']
    if not re.fullmatch('[A-Z][A-Z0-9_]{0,30}', name):
        raise ValueError('Invalid technical module name.')
    template = next((value for value in TYPES if value[0] == project['template']), None)
    if not template or project['language'] not in template[4]:
        raise ValueError('This language and module type are not supported.')
    _, _, kind, app_class, _ = template
    directory.mkdir(parents=True, exist_ok=True)
    if kind == 'R4L':
        library(context, directory, project)
    else:
        extension = 'c' if project['language'] == 'C' else 'zig'
        lines = ['R4OS_MODULE_MANIFEST=2', 'KIND=' + kind, 'NAME=' + name, 'VERSION=0.1.0',
                 'LANGUAGE=' + project['language'], 'SOURCE=src/main.' + extension]
        if kind == 'R4X':
            lines += ['ENTRY_MODE=app', 'APP_CLASS=' + app_class]
        target = '/R4OS/SOFTWARE/' + name + '.' + kind
        if project['template'] == 'subsystem':
            subsystem_id = 'studio.' + project['id']
            lines += ['MODULE_ROLE=subsystem', 'SUBSYSTEM_ID=' + subsystem_id,
                      'SUBSYSTEM_DISPLAY_NAME=' + project['name']]
            if not project.get('guestFormats'):
                raise ValueError('Enter at least one guest format.')
            lines += ['GUEST_FORMAT=' + value for value in project['guestFormats']]
            target = '/R4OS/SUBSYSTEMS/' + subsystem_id + '/' + name + '.R4X'
        lines += ['TARGET=' + target, 'IMAGE_SCOPE=none']
        imports = ['R4DEV'] if kind in ('R4D', 'R4P') else ['R4SYS']
        if app_class == 'gui':
            imports += ['R4DESK', 'R4DRAW']
        lines += ['IMPORT=' + value + ':Query:1' for value in imports]
        if kind == 'R4D':
            lines += ['META=r4d.name=' + name, 'META=r4d.type=misc']
            source = DRIVER
        elif kind == 'R4P':
            lines += ['META=r4p.name=' + name, 'META=r4p.role=misc.' + name.lower(), 'META=r4p.category=misc']
            source = PROTOCOL.replace('{role}', name.lower())
        elif extension == 'c':
            source = '#include <r4os/app_contract.h>\nint32_t r4_app_main(R4App *app) { (void)app; return 0; }\n'
        elif app_class == 'console':
            source = (context['paths']['sdk'] / 'Templates/R4X/ZigConsole/src/main.zig').read_text()
        else:
            source = 'const r4os = @import("r4os");\npub fn r4_app_main(app: *r4os.App) i32 { _ = app; return 0; }\n'
        write(directory, 'module.R4MF', '\n'.join(lines) + '\n')
        write(directory, 'src/main.' + extension, source)
    write(directory, 'build.zig', BUILD)
    sdk_pin = context['pins']['sdk']
    write(directory, 'build.zig.zon', '''.{
    .name = .r4os_studio_project,
    .version = "0.1.0",
    .fingerprint = 0x17b105fe7653a449,
    .minimum_zig_version = "0.16.0",
    .dependencies = .{ .r4os_sdk = .{
        .url = "https://github.com/R4OSDev/r4os-sdk/archive/''' + sdk_pin['revision'] + '''.tar.gz",
        .hash = "''' + sdk_pin['zigPackageHash'] + '''",
    } },
    .paths = .{ ''' + ', '.join(json.dumps(value) for value in (
        ['build.zig', 'build.zig.zon', 'module.R4MF', 'THIRD_PARTY_NOTICES.md']
        + (['Source', 'Contract', 'Bindings', 'Tests', 'Docs'] if kind == 'R4L' else ['src'])
        + [value + '.R4OS-SDK' for value in ('LICENSE', 'NOTICE') if (context['paths']['sdk'] / value).is_file()]
    )) + ''' },
}
''')
    for filename in ('LICENSE', 'NOTICE'):
        if (context['paths']['sdk'] / filename).is_file():
            shutil.copyfile(context['paths']['sdk'] / filename, directory / (filename + '.R4OS-SDK'))
    write(directory, 'THIRD_PARTY_NOTICES.md', 'Skeleton derived from R4OS SDK templates at ' + sdk_pin['revision'] + '.\n'
          'Driver/protocol entry patterns: R4OSDev/r4os-driver-example 717b33b6e47a31867b766adadcb873ba6366d8d4 and '
          'r4os-protocol-example ec1944fa4c1846620899be6a896ef36238b7e6be.\nSee LICENSE.R4OS-SDK and NOTICE.R4OS-SDK.\n')
    return validate(context, directory)


def hashes(directory):
    result = {}
    for path in sorted(directory.rglob('*')):
        if path.is_symlink():
            raise ValueError('Unexpected symbolic link in project files.')
        if path.is_file():
            result[str(path.relative_to(directory))] = digest(path)
    return result
